//! The credential-less trust gate, driven end to end.
//!
//! `rdp-core/src/connection/trust.rs:20-24` named the bug these tests hold
//! fixed: the VNC path emitted `SessionEvent::CertificatePrompt` and carried
//! straight on to `Negotiating`, so a first-contact server key was approved
//! by emission rather than by a person. The fix raises the question on a
//! channel `establish_interactive` serves, exactly like the credential ask.
//!
//! The only handshake that reaches the gate credential-less is VeNCrypt
//! `X509None` (a server key and nothing else on the wire), so the fixture
//! here is a real VeNCrypt 0.2 server speaking over a duplex stream, with a
//! real TLS handshake against a self-signed key nobody has pinned. That is
//! what makes the first contact `TrustDecision::Unknown` for the same reason
//! a real one is, rather than a mocked return value.

