/// An injected transport whose every connection is a fresh mock first-contact
/// server. The client side goes to the session; the server side runs
/// [`mock_x509none`] on its own task.
struct FirstContact {
    /// Set once the mock has read ClientInit off the wire — the byte the old
    /// bug would have sent over an unapproved key.
    client_init: Arc<AtomicBool>,
}

impl StreamConnector for FirstContact {
    fn connect(&self, _host: &str, _port: u16, _timeout: Duration) -> ConnectFuture<'_> {
        let (client, server) = tokio::io::duplex(256 * 1024);
        let client_init = self.client_init.clone();
        tokio::spawn(async move {
            let _ = mock_x509none(server, client_init).await;
        });
        Box::pin(async move { Ok(Box::pin(client) as BoxedStream) })
    }

    fn describe(&self) -> String {
        "mock first-contact VeNCrypt server".to_string()
    }
}

/// Serve one connection the way a first-contact `X509None` server would:
/// VeNCrypt 0.2, a TLS handshake with the self-signed fixture key, a
/// SecurityResult, and then nothing but the RFB session — no credential
/// exchange anywhere, which is what leaves `establish`'s gate holding a
/// credential-less first contact.
async fn mock_x509none(
    mut s: tokio::io::DuplexStream,
    client_init: Arc<AtomicBool>,
) -> std::io::Result<()> {
    // RFB 3.8, one security type on offer: VeNCrypt.
    s.write_all(b"RFB 003.008\n").await?;
    let mut banner = [0u8; 12];
    s.read_exact(&mut banner).await?;
    s.write_all(&[1, 19]).await?;
    let mut chosen = [0u8; 1];
    s.read_exact(&mut chosen).await?;
    assert_eq!(chosen[0], 19, "the client must choose VeNCrypt");

    // VeNCrypt 0.2, subtype list of one: X509None (260, four-byte form).
    s.write_all(&[0, 2]).await?;
    let mut version = [0u8; 2];
    s.read_exact(&mut version).await?;
    s.write_all(&[0]).await?;
    s.write_all(&[1, 0, 0, 1, 4]).await?;
    let mut subtype = [0u8; 4];
    s.read_exact(&mut subtype).await?;
    assert_eq!(u32::from_be_bytes(subtype), 260, "X509None and nothing else");
    s.write_all(&[1]).await?;

    // The TLS handshake. The client has no pin for this key and cannot chain
    // it to a root, so its verifier records `TrustDecision::Unknown` — the
    // first contact the whole file is about.
    let acceptor =
        tokio_rustls::TlsAcceptor::from(Arc::new(server_config()));
    let mut tls = acceptor.accept(s).await.expect("tls handshake");

    // SecurityResult OK; VeNCrypt always reports one.
    tls.write_all(&0u32.to_be_bytes()).await?;

    // ClientInit: the first RFB byte after the security phase. The tests read
    // the flag to see whether anything crossed an unapproved stream.
    let mut shared = [0u8; 1];
    tls.read_exact(&mut shared).await?;
    client_init.store(true, Ordering::SeqCst);

    // ServerInit: 640x480, 32bpp true colour, name "mock".
    let mut pf = [0u8; 16];
    pf[0] = 32;
    pf[1] = 24;
    pf[3] = 1;
    pf[4..6].copy_from_slice(&255u16.to_be_bytes());
    pf[6..8].copy_from_slice(&255u16.to_be_bytes());
    pf[8..10].copy_from_slice(&255u16.to_be_bytes());
    pf[10] = 16;
    pf[11] = 8;
    let mut init = Vec::new();
    init.extend_from_slice(&640u16.to_be_bytes());
    init.extend_from_slice(&480u16.to_be_bytes());
    init.extend_from_slice(&pf);
    init.extend_from_slice(&4u32.to_be_bytes());
    init.extend_from_slice(b"mock");
    tls.write_all(&init).await?;

    // Hold the session open until the client goes away.
    let mut buf = [0u8; 256];
    while let Ok(n) = tls.read(&mut buf).await {
        if n == 0 {
            break;
        }
    }
    Ok(())
}

