/// The bug, stated from its fix: a credential-less first contact must PARK on
/// the answer. No `Negotiating`, no `Connected`, and not one byte of
/// ClientInit over the wire until a person has approved the key — and then it
/// continues as if nothing had happened, asking no second dialog.
#[tokio::test]
async fn a_credential_less_first_contact_does_not_reach_negotiating_until_approved() {
    let (attempt, mut gate) = Gate::open(Duration::from_secs(30)).await;
    let (fingerprint, subject, scheme) = gate.prompt().await;
    assert_eq!(scheme, PinScheme::Tls, "the VeNCrypt key is the TLS key");
    assert!(
        subject.contains("vnc-core"),
        "the dialog carries the certificate subject: {subject}"
    );

    // With the question on screen NOTHING moves: not one further event, and
    // not one byte of ClientInit.
    assert!(
        tokio::time::timeout(Duration::from_millis(300), gate.events.recv())
            .await
            .is_err(),
        "the session must park on the answer, not carry straight on"
    );
    assert!(
        !gate.client_init.load(Ordering::SeqCst),
        "ClientInit must not precede the approval"
    );

    // The answer round trips through a UI that dropped the colons and
    // lowercased the hex: the comparison normalises, it never compares raw
    // strings.
    gate.answer(
        fingerprint.to_ascii_lowercase().replace(':', "").as_str(),
        scheme,
    )
    .await;

    gate.negotiating().await;
    attempt
        .await
        .unwrap()
        .expect("an approved first contact establishes");
    assert!(
        gate.client_init.load(Ordering::SeqCst),
        "after the approval the handshake completes"
    );
    gate.assert_prompt_gated_the_negotiation();
}

/// Refusing — the cancel button, a disconnect, a shell that goes away, a
/// cancelled session — unwinds the attempt with a clear error and nothing
/// sent over the unapproved stream. ClientInit is the first byte that would
/// have crossed it, and the mock records every one that arrives.
#[tokio::test]
async fn refusing_the_prompt_unwinds_the_attempt_with_nothing_sent() {
    for answer in [ClientCommand::CancelCredentials, ClientCommand::Disconnect] {
        let (attempt, mut gate) = Gate::open(Duration::from_secs(30)).await;
        gate.prompt().await;
        gate.commands.send(answer).await.expect("send");
        let err = attempt
            .await
            .unwrap()
            .err()
            .expect("a refused key must not establish");
        assert!(matches!(err, VncError::CertificateUntrusted(_)), "{err}");
        assert!(
            err.needs_user_action(),
            "the supervisor must stop and tell the user, not retry"
        );
        assert!(!err.is_transient(), "and must not back off into the dialog");
        assert!(
            !gate.client_init.load(Ordering::SeqCst),
            "nothing may be sent over an unapproved stream"
        );
        gate.assert_never_negotiated();
        gate.assert_no_credentials_required();
    }

    // A shell that goes away with the dialog open: nobody can answer, so the
    // key stays unapproved.
    let (attempt, gate) = Gate::open(Duration::from_secs(30)).await;
    let Gate {
        commands,
        client_init,
        ..
    } = gate;
    drop(commands);
    let err = attempt.await.unwrap().err().expect("no shell, no approval");
    assert!(matches!(err, VncError::Cancelled), "{err}");
    assert!(!client_init.load(Ordering::SeqCst));

    // And a cancellation while the dialog is open.
    let (attempt, mut gate) = Gate::open(Duration::from_secs(30)).await;
    gate.prompt().await;
    gate.cancel.cancel();
    let err = attempt.await.unwrap().err().expect("cancelled mid-prompt");
    assert!(matches!(err, VncError::Cancelled), "{err}");
    assert!(!gate.client_init.load(Ordering::SeqCst));
}

/// An answer that names another key, or the same key under another scheme,
/// approves nothing — the comparison is the credential gate's own, on
/// normalised fingerprint AND scheme.
#[tokio::test]
async fn an_answer_naming_another_key_or_scheme_approves_nothing() {
    // A stale approval from an earlier dialog, or one for a different host.
    let (attempt, mut gate) = Gate::open(Duration::from_secs(30)).await;
    gate.prompt().await;
    gate.commands
        .send(ClientCommand::TrustCertificate {
            fingerprint: "AA:BB:CC:DD".into(),
            permanent: false,
            scheme: PinScheme::Tls,
        })
        .await
        .expect("send");
    let err = attempt
        .await
        .unwrap()
        .err()
        .expect("another key approves nothing");
    assert!(matches!(err, VncError::CertificateUntrusted(_)), "{err}");
    assert!(!gate.client_init.load(Ordering::SeqCst));
    gate.assert_never_negotiated();

    // The right key under the other protocol's scheme: one protocol's
    // approval may not vouch for the other's key of the same host.
    let (attempt, mut gate) = Gate::open(Duration::from_secs(30)).await;
    let (fingerprint, _, _) = gate.prompt().await;
    gate.answer(&fingerprint, PinScheme::Ra2).await;
    let err = attempt
        .await
        .unwrap()
        .err()
        .expect("the wrong scheme approves nothing");
    assert!(matches!(err, VncError::CertificateUntrusted(_)), "{err}");
    assert!(!gate.client_init.load(Ordering::SeqCst));
    gate.assert_never_negotiated();
}

/// The connect deadline is PAUSED while the person reads, exactly as it is
/// while they type a password: a fingerprint being compared against the
/// host's documentation is not the connect stalling. Three times the budget
/// is spent with the dialog open here, and the connect must still complete
/// after the approval.
#[tokio::test]
async fn the_deadline_is_not_consumed_while_the_person_reads() {
    let (attempt, mut gate) = Gate::open(Duration::from_millis(400)).await;
    let (fingerprint, _, scheme) = gate.prompt().await;

    // Several budgets' worth of reading time.
    tokio::time::sleep(Duration::from_millis(1200)).await;

    gate.answer(&fingerprint, scheme).await;
    let established = tokio::time::timeout(WAIT, attempt)
        .await
        .expect("time spent reading must not eat the connect budget")
        .unwrap();
    established.expect("approved after a slow read still connects");
    gate.negotiating().await;
    assert!(gate.client_init.load(Ordering::SeqCst));
    gate.assert_prompt_gated_the_negotiation();
}
