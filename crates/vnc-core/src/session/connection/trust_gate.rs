/// How long any single wait in these tests may take. Generous: the property
/// under test is never "fast", it is "not until the person answers".
const WAIT: Duration = Duration::from_secs(10);

/// One `establish_interactive` driving a mock first-contact server, with the
/// event history kept so the end-of-test assertions can see everything the
/// session said, not just the last thing.
struct Gate {
    events: mpsc::Receiver<SessionEvent>,
    commands: mpsc::Sender<ClientCommand>,
    cancel: CancellationToken,
    client_init: Arc<AtomicBool>,
    seen: Vec<SessionEvent>,
}

impl Gate {
    /// Start one attempt; the handle is the attempt itself, kept out of the
    /// struct so the tests can await it without borrowing the gate.
    async fn open(deadline: Duration) -> (tokio::task::JoinHandle<Result<Established>>, Self) {
        let client_init = Arc::new(AtomicBool::new(false));
        let mut options = ConnectOptions::vnc("vnc-test", 5900);
        options.connector = Some(Connector(Arc::new(FirstContact {
            client_init: client_init.clone(),
        })));
        options.connect_deadline = deadline;
        let settings = SessionSettings::from_options(&options);
        let (events_tx, events_rx) = mpsc::channel(32);
        let (commands_tx, mut commands_rx) = mpsc::channel(8);
        let cancel = CancellationToken::new();
        let run_cancel = cancel.clone();
        let attempt = tokio::spawn(async move {
            establish_interactive(&mut options, &settings, &events_tx, &mut commands_rx, &run_cancel)
                .await
        });
        (
            attempt,
            Gate {
                events: events_rx,
                commands: commands_tx,
                cancel,
                client_init,
                seen: Vec::new(),
            },
        )
    }

    /// Wait for the certificate prompt, keeping every event seen on the way.
    /// Returns `(fingerprint, subject, scheme)` as the dialog would show them.
    async fn prompt(&mut self) -> (String, String, PinScheme) {
        tokio::time::timeout(WAIT, async {
            loop {
                let ev = self.events.recv().await.expect("the session keeps emitting");
                let matched = match &ev {
                    SessionEvent::CertificatePrompt {
                        fingerprint,
                        subject,
                        is_change,
                        scheme,
                    } => {
                        assert!(!*is_change, "first contact is never a changed pin");
                        assert!(!subject.is_empty(), "the dialog has a subject to show");
                        Some((fingerprint.clone(), subject.clone(), *scheme))
                    }
                    SessionEvent::Error(e) => panic!("the connect failed before prompting: {e}"),
                    _ => None,
                };
                self.seen.push(ev);
                if let Some(m) = matched {
                    break m;
                }
            }
        })
        .await
        .expect("the certificate prompt must arrive")
    }

    /// Answer the open prompt with `ClientCommand::TrustCertificate`.
    async fn answer(&self, fingerprint: &str, scheme: PinScheme) {
        self.commands
            .send(ClientCommand::TrustCertificate {
                fingerprint: fingerprint.to_string(),
                permanent: false,
                scheme,
            })
            .await
            .expect("the session is still listening");
    }

    /// Wait for `Negotiating`, keeping every event seen on the way.
    async fn negotiating(&mut self) {
        tokio::time::timeout(WAIT, async {
            loop {
                let ev = self.events.recv().await.expect("the session keeps emitting");
                if let SessionEvent::Error(e) = &ev {
                    panic!("the approved connect failed: {e}");
                }
                let done =
                    matches!(&ev, SessionEvent::StateChanged(SessionState::Negotiating));
                self.seen.push(ev);
                if done {
                    break;
                }
            }
        })
        .await
        .expect("Negotiating once the key is approved");
    }

    /// The end state of an approved first contact: one prompt, no credential
    /// dialog anywhere (this subtype has no credentials to ask for, and the
    /// UI must only ever see `CertificatePrompt`), and the negotiation behind
    /// the prompt rather than in front of it.
    fn assert_prompt_gated_the_negotiation(&self) {
        let prompt_at = self
            .seen
            .iter()
            .position(|e| matches!(e, SessionEvent::CertificatePrompt { .. }))
            .expect("the certificate prompt");
        let negotiating_at = self
            .seen
            .iter()
            .position(|e| matches!(e, SessionEvent::StateChanged(SessionState::Negotiating)))
            .expect("Negotiating after the approval");
        assert!(
            prompt_at < negotiating_at,
            "the prompt must gate the negotiation: {:?}",
            self.seen
        );
        let prompts = self
            .seen
            .iter()
            .filter(|e| matches!(e, SessionEvent::CertificatePrompt { .. }))
            .count();
        assert_eq!(prompts, 1, "one dialog for one key, not two");
        self.assert_no_credentials_required();
    }

    /// The end state of a refused first contact: the attempt never moved past
    /// the prompt.
    fn assert_never_negotiated(&self) {
        assert!(
            self.seen
                .iter()
                .all(|e| !matches!(
                    e,
                    SessionEvent::StateChanged(SessionState::Negotiating)
                        | SessionEvent::StateChanged(SessionState::Connected)
                )),
            "a refused key must stop the session before Negotiating: {:?}",
            self.seen
        );
    }

    fn assert_no_credentials_required(&self) {
        assert!(
            !self
                .seen
                .iter()
                .any(|e| matches!(e, SessionEvent::CredentialsRequired(_))),
            "a credential-less subtype must never raise CredentialsRequired: {:?}",
            self.seen
        );
    }
}

